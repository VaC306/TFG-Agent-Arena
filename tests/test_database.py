import sqlite3
import pytest
from arena.database import connect, database_target, postgres_sql, postgres_schema


def test_database_configuration_priority(monkeypatch):
    monkeypatch.setenv('ARENA_DB', 'local.sqlite')
    monkeypatch.delenv('ARENA_DATABASE_URL', raising=False)
    assert database_target() == 'local.sqlite'
    monkeypatch.setenv('ARENA_DATABASE_URL', 'postgresql://example/arena')
    assert database_target() == 'postgresql://example/arena'


def test_sqlite_transaction_rollback_and_close(tmp_path):
    with connect(tmp_path / 'nested' / 'test.sqlite') as db:
        db.execute('CREATE TABLE probe(value TEXT)')
    with pytest.raises(ValueError):
        with connect(tmp_path / 'nested' / 'test.sqlite') as db:
            db.execute('INSERT INTO probe VALUES (?)', ('secret',))
            raise ValueError('rollback')
    with connect(tmp_path / 'nested' / 'test.sqlite') as db:
        assert db.execute('SELECT COUNT(*) FROM probe').fetchone()[0] == 0
    with pytest.raises(sqlite3.ProgrammingError):
        db.execute('SELECT 1')


def test_postgres_sql_keeps_literals_and_binds_values():
    sql = "SELECT json_extract(e.snapshot, '$.config.name') FROM experiments e WHERE (? IS NULL OR id=?) AND '?'='?'"
    converted = postgres_sql(sql)
    assert "e.snapshot::jsonb #>> '{config,name}'" in converted
    assert 'CAST(%s AS TEXT) IS NULL OR id=%s' in converted
    assert "'?'='?'" in converted


def test_postgres_schema_preserves_timestamp_precision():
    sql = postgres_schema('PRAGMA journal_mode=WAL; CREATE TABLE IF NOT EXISTS experiments(id TEXT PRIMARY KEY, at REAL); CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY AUTOINCREMENT);')
    assert 'PRAGMA' not in sql
    assert 'DOUBLE PRECISION' in sql
    assert 'rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE' in sql
    assert 'seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in sql
