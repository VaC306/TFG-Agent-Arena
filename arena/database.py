"""SQLite/PostgreSQL connections for the arena repository's SQL dialect.

Only repository SQL is adapted here; values always remain bound parameters.
PostgreSQL tables live in an unexposed schema, separate from Supabase's public API.
"""
import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path


def database_target(default='runtime/arena.sqlite'):
    return os.environ.get('ARENA_DATABASE_URL') or os.environ.get('ARENA_DB') or default


def is_postgres(target):
    return str(target).startswith(('postgresql://', 'postgres://'))


class Record(dict):
    """Retain the named and positional access used by sqlite3.Row callers."""
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def record_factory(cursor):
    if cursor.description is None:
        return lambda values: Record()
    names = [column.name for column in cursor.description]
    return lambda values: Record(zip(names, values))


def postgres_sql(sql):
    # These expressions are deliberately limited to literal JSON paths in our SQL.
    sql = re.sub(r"json_extract\((\w+\.\w+),\s*'\$\.([\w.]+)'\)",
                 lambda m: "(" + m[1] + "::jsonb #>> '{" + m[2].replace('.', ',') + "}')", sql)
    # PostgreSQL must know the type of a standalone nullable owner parameter.
    sql = sql.replace('? IS NULL', 'CAST(? AS TEXT) IS NULL')
    # Ignore question marks inside SQL literals, and escape percent signs for psycopg.
    parts = re.split(r"('(?:''|[^'])*')", sql)
    return ''.join(part.replace('%', '%%').replace('?', '%s') if i % 2 == 0
                   else part.replace('%', '%%') for i, part in enumerate(parts))


def postgres_schema(sql):
    sql = re.sub(r'PRAGMA[^;]+;', '', sql)
    sql = sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
    # Preserve insertion ordering, including equal timestamps, without SQLite rowid.
    for table in ('experiments', 'runs', 'campaigns', 'attempt_annotations', 'library_items'):
        sql = sql.replace(f'CREATE TABLE IF NOT EXISTS {table}(',
                          f'CREATE TABLE IF NOT EXISTS {table}(rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,')
    return sql


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, parameters=()):
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            # Preserve the existing single-writer critical sections, including the
            # single active run across workers. The lock is released on commit/rollback.
            return self.connection.execute('SELECT pg_advisory_xact_lock(742019861)')
        if sql.strip().upper() == 'BEGIN':
            return self.connection.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ')
        return self.connection.execute(postgres_sql(sql), parameters)

    def executemany(self, sql, parameters):
        with self.connection.cursor() as cursor:
            cursor.executemany(postgres_sql(sql), parameters)

    def executescript(self, sql):
        self.connection.execute('SELECT pg_advisory_xact_lock(742019862)')
        for statement in postgres_schema(sql).split(';'):
            if statement.strip():
                self.connection.execute(statement)


@contextmanager
def connect(target):
    if not is_postgres(target):
        Path(target).parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(str(target), timeout=30)
        try:
            with db:
                db.row_factory = sqlite3.Row
                db.execute('PRAGMA foreign_keys=ON')
                yield db
        finally:
            db.close()
        return
    try:
        import psycopg
    except ImportError:
        raise RuntimeError('Instala requirements-postgres.lock para conectar a PostgreSQL.') from None
    # URL and provider exceptions must never be echoed: they may contain secrets.
    try:
        options = psycopg.conninfo.conninfo_to_dict(str(target))
        local = options.get('host') in {'localhost', '127.0.0.1', '::1'}
        mode = options.get('sslmode', 'prefer' if local else 'require')
        if not local and mode not in {'require', 'verify-ca', 'verify-full'}:
            raise ValueError('La conexión remota a PostgreSQL requiere SSL.')
        db = psycopg.connect(str(target), connect_timeout=10, sslmode=mode,
                             prepare_threshold=None, row_factory=record_factory)
    except psycopg.Error:
        raise RuntimeError('No se pudo conectar a PostgreSQL. Revisa host, SSL y credenciales locales.') from None
    try:
        with db:
            db.execute("SET search_path TO arena, pg_catalog")
            yield PostgresConnection(db)
    except psycopg.IntegrityError:
        # Keep the repository's existing duplicate-account error handling portable.
        raise sqlite3.IntegrityError('Database integrity constraint violated') from None


def initialize_postgres(target):
    with connect(target) as db:
        db.connection.execute('SELECT pg_advisory_xact_lock(742019862)')
        db.connection.execute('CREATE SCHEMA IF NOT EXISTS arena')
        db.connection.execute('REVOKE ALL ON SCHEMA arena FROM PUBLIC')
